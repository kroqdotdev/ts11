export const GLYPH_W = 5;
export const GLYPH_H = 7;

const CACHE = new Map<string, boolean[]>();

function glyph(ch: string): boolean[] {
  const key = ch.toUpperCase();
  let g = CACHE.get(key);
  if (!g) {
    const src = GLYPHS[key] ?? GLYPHS["?"];
    g = src
      .replace(/ /g, "")
      .split("")
      .map((c) => c === "1");
    CACHE.set(key, g);
  }
  return g;
}

export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale;
}

/** Calls `plot` for every lit pixel of `text` drawn at (x, y). */
export function eachTextPixel(
  text: string,
  x: number,
  y: number,
  scale: number,
  plot: (px: number, py: number) => void,
) {
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (!g[r * GLYPH_W + c]) continue;
        for (let sy = 0; sy < scale; sy++)
          for (let sx = 0; sx < scale; sx++) plot(cx + c * scale + sx, y + r * scale + sy);
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}

/** Reduces any text to what the pixel font can draw: A to Z, digits and a little punctuation. */
export function toBoardText(text: string): string {
  return text
    .replace(/æ/gi, "AE")
    .replace(/ø/gi, "O")
    .replace(/ß/g, "SS")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^A-Z0-9 \-:.,!?'&+/]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}
